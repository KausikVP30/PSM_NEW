#!/usr/bin/env python3
"""
Wrapper script to run experiment with timestamped outputs and latency metrics.
Usage: python run_experiment_gpu.py --config config_gpu_run.yaml --gpu-index 0
"""

import argparse
import json
import os
import sys
import time
from datetime import datetime
from pathlib import Path
import subprocess

from scripts.ollama_shared_gpu import select_cuda_visible_devices_if_unassigned

def main():
    parser = argparse.ArgumentParser(description="Run experiment on GPU with timestamped outputs")
    parser.add_argument("--config", default="config_gpu_run.yaml", help="Config file path")
    parser.add_argument("--gpu-index", type=int, default=None, help="GPU index to use; defaults to max-free GPU")
    parser.add_argument("--mode", default=None, help="Override run mode (smoke/subset/full)")
    args = parser.parse_args()

    # Set CUDA visible devices without disturbing other users' processes.
    if args.gpu_index is None:
        selected_gpu = select_cuda_visible_devices_if_unassigned()
        if selected_gpu is None:
            selected_gpu = os.environ.get("CUDA_VISIBLE_DEVICES", "0")
        args.gpu_index = int(str(selected_gpu).split(",")[0])
    os.environ["CUDA_VISIBLE_DEVICES"] = str(args.gpu_index)
    os.environ.setdefault("OLLAMA_ENDPOINT", "http://127.0.0.1:11435")
    
    # Create timestamp for output files
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    
    # Prepare output directories
    output_dir = Path("outputs")
    predictions_dir = output_dir / "predictions"
    metrics_dir = output_dir / "metrics"
    logs_dir = output_dir / "logs"
    
    for d in [predictions_dir, metrics_dir, logs_dir]:
        d.mkdir(parents=True, exist_ok=True)
    
    # Generate timestamped output filenames
    predictions_file = predictions_dir / f"predictions_gpu{args.gpu_index}_{timestamp}.csv"
    metrics_file = metrics_dir / f"metrics_gpu{args.gpu_index}_{timestamp}.json"
    log_file = logs_dir / f"run_gpu{args.gpu_index}_{timestamp}.log"
    
    # Build command
    cmd = [
        sys.executable,
        "run_experiment.py",
        "--config", args.config,
    ]
    
    if args.mode:
        cmd.extend(["--mode", args.mode])
    
    # Measure experiment runtime
    print(f"🚀 Starting experiment on GPU {args.gpu_index}")
    print(f"📊 Predictions will be saved to: {predictions_file}")
    print(f"📈 Metrics will be saved to: {metrics_file}")
    print(f"📝 Log file: {log_file}")
    print("-" * 80)
    
    start_time = time.time()
    try:
        # Run the experiment
        result = subprocess.run(cmd, cwd=Path.cwd(), capture_output=False, text=True, check=True)
        elapsed_time = time.time() - start_time

        standard_predictions_file = predictions_dir / "predictions.csv"
        
        # Load the metrics that were generated by the experiment
        standard_metrics_file = metrics_dir / "metrics.json"
        if standard_metrics_file.exists():
            with open(standard_metrics_file, 'r') as f:
                metrics = json.load(f)
            
            # Add GPU information and rename the file to timestamped version
            metrics["gpu_index"] = args.gpu_index
            metrics["experiment_timestamp"] = timestamp
            metrics["total_latency_seconds"] = elapsed_time
            
            # Save timestamped version
            with open(metrics_file, 'w') as f:
                json.dump(metrics, f, indent=2)

            if standard_predictions_file.exists():
                predictions_file.write_text(standard_predictions_file.read_text(encoding="utf-8"), encoding="utf-8")
            else:
                print(f"⚠️  Warning: standard predictions file not found at {standard_predictions_file}")
            
            print("-" * 80)
            print(f"✅ Experiment completed successfully!")
            print(f"⏱️  Total latency: {elapsed_time:.2f} seconds")
            print(f"🎯 GPU Index: {args.gpu_index}")
            print(f"\n📊 Metrics saved to: {metrics_file}")
            print(f"📁 Predictions saved to: {predictions_file}")
            print(f"\nKey Metrics:")
            for key, value in metrics.items():
                if key not in ['gpu_index', 'experiment_timestamp']:
                    print(f"  {key}: {value}")
        else:
            print("⚠️  Warning: Standard metrics file not found")
            
    except subprocess.CalledProcessError as e:
        elapsed_time = time.time() - start_time
        print("-" * 80)
        print(f"❌ Experiment failed after {elapsed_time:.2f} seconds")
        print(f"Error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
